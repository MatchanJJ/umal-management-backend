// Post-build: give every exported page a CSP that allows exactly its own inline scripts (by SHA-256).
// Next's static export inlines the page payload as <script>self.__next_f.push(...)</script>, which a plain
// `default-src 'self'` blocks (blank page). Hashes keep scripts strict; no 'unsafe-inline'.
// Runs after `next build` (see package.json "build"); appends one rule per page to out/_headers.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

/** The policy minus script-src (TRD §10: self + Google avatars; inline styles come from toasts/Radix). */
export const BASE_POLICY = [
  "default-src 'self'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' https://lh3.googleusercontent.com data:",
  "connect-src 'self'",
  "frame-ancestors 'none'",
];

// Cloudflare Pages _headers limits.
const MAX_RULES = 100;
const MAX_LINE = 2000;

/** 'sha256-…' for each inline (no src) script, in document order, deduplicated. */
export function inlineScriptHashes(html) {
  const hashes = [...html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/gi)]
    .map((m) => m[1])
    .filter((body) => body.length > 0)
    .map((body) => `'sha256-${createHash('sha256').update(body, 'utf8').digest('base64')}'`);
  return [...new Set(hashes)];
}

export function policyFor(hashes) {
  return [BASE_POLICY[0], `script-src 'self'${hashes.length ? ` ${hashes.join(' ')}` : ''}`, ...BASE_POLICY.slice(1)].join('; ');
}

/** out/dashboard/index.html → /dashboard/ ; out/index.html → / ; other .html files have no route of their own. */
export function routeFor(relPath) {
  const p = relPath.split(sep).join('/');
  if (p === 'index.html') return '/';
  return p.endsWith('/index.html') ? `/${p.slice(0, -'index.html'.length)}` : null;
}

/**
 * Rules to append: each detaches the catch-all CSP (`! Content-Security-Policy`), because Pages joins
 * duplicate headers with a comma and a browser would enforce both policies.
 */
export function pageRules(pages) {
  const rules = pages.map(({ route, html }) => `${route}\n  ! Content-Security-Policy\n  Content-Security-Policy: ${policyFor(inlineScriptHashes(html))}`);
  for (const r of rules) for (const line of r.split('\n')) if (line.length > MAX_LINE) throw new Error(`_headers line over ${MAX_LINE} chars: ${line.slice(0, 80)}…`);
  return rules;
}

function htmlFiles(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? htmlFiles(p) : name.endsWith('.html') ? [p] : [];
  });
}

function main(outDir = 'out') {
  const pages = htmlFiles(outDir).flatMap((file) => {
    const route = routeFor(relative(outDir, file));
    return route ? [{ route, html: readFileSync(file, 'utf8') }] : [];
  });
  const headersFile = join(outDir, '_headers');
  // The catch-all policy also serves 404.html (unknown paths), so it gets that page's hashes.
  const fallback = `script-src 'self' ${inlineScriptHashes(readFileSync(join(outDir, '404.html'), 'utf8')).join(' ')};`;
  const raw = readFileSync(headersFile, 'utf8').trimEnd();
  if (!raw.includes("script-src 'self';")) throw new Error(`public/_headers must contain "script-src 'self';" in its catch-all CSP`);
  const base = raw.replace("script-src 'self';", fallback);
  const total = (base.match(/^\S/gm) ?? []).length + pages.length;
  if (total > MAX_RULES) throw new Error(`_headers would have ${total} rules (Pages allows ${MAX_RULES})`);
  writeFileSync(headersFile, `${base}\n\n# Generated by scripts/csp-headers.mjs: per-page script hashes.\n${pageRules(pages).join('\n')}\n`);
  console.log(`csp-headers: ${pages.length} pages hashed into ${headersFile}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main(process.argv[2]);
